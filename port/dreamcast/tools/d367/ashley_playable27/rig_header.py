#!/usr/bin/env python3
"""Pin the playable pl01 rig's independently converted hand contracts.

rig_header.py OUTPUT CONVERSION [CONVERSION ...]
No geometry or texture bytes enter Git. Only the private build gets this header.
"""
import hashlib
import json
import sys
from pathlib import Path


def generate(output, convs):
    if not convs:
        raise ValueError('At least one playable conversion is required')
    text = ['// Generated by ashley_playable27/rig_header.py; private build input.',
            '#pragma once', 'namespace ashley_playable_ps2_rig27 {',
            'constexpr unsigned version=1;',
            '// This nominates a descriptor only. Runtime also proves pPL/OT7 and',
            '// all seven adopted player-family BIN/TPL role certificates.',
            'constexpr bool shape(unsigned model,unsigned joints,unsigned roles) {',
            ' return model==0u && joints==141u && roles==7u;', '}']
    maps = []
    for i, p in enumerate(convs):
        raw = (p / 'source.json').read_bytes()
        s = json.loads(raw)
        rig = s.get('ps2_rig', {})
        infos = [(x['source_bin_arc'], x['source_tpl_arc']) for x in s['infos']]
        if (s.get('source_archive') != 'pl01' or s.get('source_model_id') != 0 or
                rig.get('schema') != 'ashley-ps2-rig-1' or rig.get('ps2_bones') != 81 or
                rig.get('shared_bones') != 64 or len(s.get('bones', [])) != 141 or len(infos) != 7 or
                infos[:5] != [(4, 5), (7, 9), (6, 11), (8, 5), (10, 5)] or
                infos[5] not in [(17, 5), (167, 168)] or infos[6] not in [(20, 5), (21, 5)]):
            raise ValueError(f'{p}: exact playable pl01 rig/source role contract required')
        slots = s['draw_slots']
        if len(slots) > 64 or slots != sorted(set(slots)) or any(not 0 <= x < 141 for x in slots):
            raise ValueError('Invalid playable rig slot map')
        if slots in maps:
            continue
        maps.append(slots)
        text += [f'// source.json sha256 {hashlib.sha256(raw).hexdigest()}',
                 f'constexpr unsigned char slots{len(maps)-1}[]={{'+','.join(map(str, slots))+'};']
    text += ['inline bool slots_match(const unsigned char* slots,unsigned count) {',
             ' const unsigned char* maps[]={'+','.join(f'slots{i}' for i in range(len(maps)))+'};',
             ' const unsigned sizes[]={'+','.join(f'sizeof(slots{i})' for i in range(len(maps)))+'};',
             f' for(unsigned h=0;h<{len(maps)}u;++h) {{',
             '  if(count!=sizes[h])continue;',
             '  unsigned i=0;while(i<count && slots[i]==maps[h][i])++i;',
             '  if(i==count)return true;', ' }', ' return false;', '}', '}']
    output.mkdir(parents=True, exist_ok=True)
    (output / 'ashley_playable_ps2_rig27.h').write_text('\n'.join(text)+'\n')


if __name__ == '__main__':
    generate(Path(sys.argv[1]), [Path(x) for x in sys.argv[2:]])
