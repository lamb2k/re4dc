#!/usr/bin/env python3
"""Bind an ASHLEY_PS2_RIG build to its three privately converted hand sets.

rig_header.py <conv0> <conv1> <conv3> <output dir>
Only slot indices and hashes enter the header. Game assets stay private.
"""
import hashlib
import json
import sys
from pathlib import Path


def generate(convs, output):
    sources = [json.loads((p / 'source.json').read_text()) for p in convs]
    text = ['// Generated by ashley_rig27/rig_header.py; private build input.', '#pragma once',
            'namespace ashley_ps2_rig27 {', 'constexpr unsigned version=1;']
    for k, (p, s) in enumerate(zip(convs, sources)):
        rig = s.get('ps2_rig', {})
        if rig.get('schema') != 'ashley-ps2-rig-1' or rig.get('ps2_bones') != 81:
            raise ValueError(f'{p}: PS2 rig source required')
        if rig != sources[0]['ps2_rig']:
            raise ValueError('Hand sets disagree on the PS2 rig')
        slots = s['draw_slots']
        if len(slots) > 64 or slots != sorted(set(slots)):
            raise ValueError('Invalid rig slot map')
        text += [f'// source.json sha256 {hashlib.sha256((p / "source.json").read_bytes()).hexdigest()}',
                 f'constexpr unsigned char slots{k}[]={{' + ','.join(map(str, slots)) + '};']
    text += ['inline bool slots_match(const unsigned char* slots,unsigned count) {',
             '    const unsigned char* maps[]={slots0,slots1,slots2};',
             '    const unsigned sizes[]={sizeof(slots0),sizeof(slots1),sizeof(slots2)};',
             '    for(unsigned h=0;h<3;++h) {',
             '        if(count!=sizes[h])continue;',
             '        unsigned i=0;while(i<count && slots[i]==maps[h][i])++i;',
             '        if(i==count)return true;', '    }', '    return false;', '}', '}']
    output.mkdir(parents=True, exist_ok=True)
    (output / 'ashley_ps2_rig27.h').write_text('\n'.join(text) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 5:
        raise SystemExit(__doc__)
    generate([Path(x) for x in sys.argv[1:4]], Path(sys.argv[4]))
