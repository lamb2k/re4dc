#!/usr/bin/env python3
"""Chapter 3 (castle 3-1 .. 3-4) PS2 enemy-list rows: audit the full 32-byte PS2 USA records against the GameCube
lists and emit a PRIVATE fresh-read patch table (ps2_enemy_ch3_data.inc) for platform/ps2_enemy_ch3.cpp.

Castle lane 2026-10-15, PS2_CH3_ENEMY. Same record handling as ps2_enemy_ch23.py (GC big endian, PS2 little
endian, all 32 bytes kept, every selected baseline byte checked at runtime before anything is written).

Rooms: emleon02 (3-1) r201 r203 r207 r208; emleon03 (3-2 .. 3-4) r204 r20e. The other chapter 3 rooms have no
row difference. r205 is left out on purpose: the PS2 list holds 0x57 / 0x6D back and its R205Init sends both itself
on Normal, so the Normal result equals the GC rows (PS2-ENEMY-CODE-DIFF Follow-up B); its rows would need that send.
A row whose start-alive bit the PS2 clears ("held") must be sent by ported room code; HELD_BY lists the code that
does it, and the audit refuses any other held row. No original game bytes belong in git: the .inc is private.
"""
from __future__ import annotations
import argparse, hashlib, json, struct, sys
from pathlib import Path

FORMAT = "BBBBIHBB3h3hHh4s"
ROW = 32
ROOM_INDEX = 14
TARGETS = {2: {0x201, 0x203, 0x207, 0x208}, 3: {0x204, 0x20E}}
# held rows -> the ported room code that sends them (or, for rows the PS2 never sends, the code that drops the send)
HELD_BY = {(2, 0x208): {1, 2, 4, 5, 6, 7, 8, 17}}   # R208Init, PS2_ENEMY_CASTLE bit 0x01 (sends 5,6,7,1,0x11; 2,4,8 never)
NAMES = ("be_flag", "id", "type", "set", "flag", "hp", "emset_no", "Character", "pos_x", "pos_y", "pos_z",
         "rot_x", "rot_y", "rot_z", "room", "Guard_r", "reserved")


def sha(b): return hashlib.sha256(b).hexdigest()


def decode(data, endian):
    assert data and len(data) <= 0x2000 and len(data) % ROW == 0, "ESL size"
    return list(struct.iter_unpack(endian + FORMAT, data))


def le(row): return struct.pack("<" + FORMAT, *row)


def audit(no, gc, ps2):
    old, new = decode(gc, ">"), decode(ps2, "<")
    assert len(old) == len(new), "row counts differ"
    base, repl, recs, held = [], [], [], {}
    for i, (a, b) in enumerate(zip(old, new)):
        ra, rb = a[ROOM_INDEX], b[ROOM_INDEX]
        room = rb if b[1] else ra
        if room not in TARGETS[no] and ra not in TARGETS[no]:
            continue
        if a[1] and b[1] and ra != rb:
            raise ValueError("list %d row %d: room changed" % (no, i))
        ob, nb = le(a), le(b)
        base.append((i, ob))
        if ob != nb:
            repl.append((i, nb))
        changed = [n for n, x, y in zip(NAMES, a, b) if x != y]
        if a[1] and (a[0] & 1) and not (b[0] & 1):
            held.setdefault(room, set()).add(i)
        recs.append(dict(index=i, room="r%03x" % room, changed=changed, gc_le=sha(ob), ps2=sha(nb)))
    for room in TARGETS[no]:
        if not any(r["room"] == "r%03x" % room for r in recs):
            raise ValueError("list %d: no rows for r%03x" % (no, room))
    for room, idx in held.items():
        if HELD_BY.get((no, room)) != idx:
            raise ValueError("list %d r%03x: held rows %s not covered by ported code %s" % (no, room, sorted(idx), HELD_BY.get((no, room))))
    return dict(list_no=no, gc_sha256=sha(gc), ps2_sha256=sha(ps2), selected=len(base), replaced=len(repl), records=recs,
                held={"r%03x" % k: sorted(v) for k, v in held.items()}), base, repl


def header(lists):
    out = ["/* PRIVATE generated game data. Do not commit or publish. */",
           "/* Generated by tools/d367/castle/ps2_enemy_ch3.py (castle lane). */"]
    for no, base, repl in lists:
        for name, rows in (("baseline", base), ("replacement", repl)):
            if rows:
                out.append("static const Ps2EnemyCh3Row ps2_enemy_ch3_%s_%d[] = {" % (name, no))
                out += ["    {%d, {%s}}," % (i, ",".join("0x%02x" % x for x in d)) for i, d in rows]
                out.append("};")
    out.append("static const Ps2EnemyCh3List ps2_enemy_ch3_lists[] = {")
    for no, base, repl in lists:
        out.append("    {%d, ps2_enemy_ch3_baseline_%d, %d, %s, %d}," % (
            no, no, len(base), ("ps2_enemy_ch3_replacement_%d" % no) if repl else "NULL", len(repl)))
    out += ["};", ""]
    return "\n".join(out)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--gc-dir", type=Path, required=True)
    p.add_argument("--ps2-dir", type=Path, required=True)
    p.add_argument("--audit-json", type=Path, required=True)
    p.add_argument("--header", type=Path, required=True)
    a = p.parse_args(argv)
    lists, rep = [], dict(schema="re4dc-ps2-enemy-ch3-v1", lists=[])
    try:
        for no in sorted(TARGETS):
            g = (a.gc_dir / ("emleon%02d.esl" % no)).read_bytes()
            s = (a.ps2_dir / ("ps2_emleon%02d.esl" % no)).read_bytes()
            info, base, repl = audit(no, g, s)
            rep["lists"].append(info); lists.append((no, base, repl))
    except (ValueError, AssertionError, OSError) as e:
        print("PS2_ENEMY_CH3: %s" % e, file=sys.stderr); return 1
    h = header(lists).encode("ascii")
    a.header.parent.mkdir(parents=True, exist_ok=True); a.header.write_bytes(h)
    rep["header"] = dict(path=str(a.header.resolve()), sha256=sha(h))
    a.audit_json.parent.mkdir(parents=True, exist_ok=True); a.audit_json.write_text(json.dumps(rep, indent=1) + "\n")
    print(json.dumps(dict(header=rep["header"], lists=[dict(list_no=x["list_no"], selected=x["selected"],
                     replaced=x["replaced"], held=x["held"]) for x in rep["lists"]])))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
