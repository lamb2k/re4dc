def remap(p):
    """castle / ch3found prepem outputs regenerated by ch3regen (not byte-exact: version may differ)."""
    for a, b in REMAP:
        if p.startswith(a):
            q = b + p[len(a):]
            if os.path.exists(q): return q
            if '/tex-em/' in p:  # merged tex dir -> per-enemy tex-emXX dirs
                for d in sorted(glob.glob(b + 'tex-em*/')):
                    if os.path.exists(d + os.path.basename(p)): return d + os.path.basename(p)
    return None
def sha(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''): h.update(b)
    return h.hexdigest()
