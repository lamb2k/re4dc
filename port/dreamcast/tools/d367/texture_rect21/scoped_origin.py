#!/usr/bin/env python3
"""Map scoped texture keys back to their original material keys (lane mipfix22).

The rect21 scoped worlds rewrite only the (crc, fnv) key words of R4PW part
records. Render policy (FOLIAGE_TRIM classes, MIST_CUT world parts, ...) is keyed
on the ORIGINAL texture identity, so the runtime needs scoped -> original.

Usage: scoped_origin.py --out scoped_origins.inc ORIGINAL.r4pw=SCOPED.r4pw ...
Every pair must be index-aligned: same header, same part count, every part
record byte-identical outside its first 8 bytes. A scoped key that maps to two
different original keys is an error. Output is sorted by scoped (crc, fnv).
"""
import argparse, struct, sys

HEAD = 32
PART = 16


def parts(blob):
    if blob[:4] != b'R4PW':
        raise ValueError('not R4PW')
    _v, _pl, n, _m = struct.unpack_from('<4I', blob, 4)
    return [blob[HEAD + i * PART:HEAD + (i + 1) * PART] for i in range(n)]


def pair_map(orig, scoped, label='pair'):
    a, b = parts(orig), parts(scoped)
    if len(a) != len(b):
        raise ValueError(f'{label}: part counts differ')
    if orig[4:20] != scoped[4:20]:
        raise ValueError(f'{label}: headers differ')
    m = {}
    for i, (x, y) in enumerate(zip(a, b)):
        if x[8:] != y[8:]:
            raise ValueError(f'{label}: part {i} changed outside its key')
        ko, ks = struct.unpack('<2I', x[:8]), struct.unpack('<2I', y[:8])
        if ko != ks:
            m.setdefault(ks, set()).add(ko)
    return m


def merge(maps):
    out = {}
    for m in maps:
        for k, v in m.items():
            out.setdefault(k, set()).update(v)
    bad = {k: v for k, v in out.items() if len(v) != 1}
    if bad:
        raise ValueError(f'{len(bad)} scoped keys map to several originals')
    return {k: next(iter(v)) for k, v in sorted(out.items())}


def emit(m):
    rows = ['// Generated by scoped_origin.py: {scoped crc, fnv, original crc, fnv}, sorted by scoped key.']
    rows += [f'{{0x{s[0]:08x}U,0x{s[1]:08x}U,0x{o[0]:08x}U,0x{o[1]:08x}U}},' for s, o in m.items()]
    return '\n'.join(rows) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('pairs', nargs='+')
    a = ap.parse_args()
    maps = []
    for p in a.pairs:
        o, s = p.split('=', 1)
        maps.append(pair_map(open(o, 'rb').read(), open(s, 'rb').read(), p))
    m = merge(maps)
    open(a.out, 'w').write(emit(m))
    print(f'{len(m)} scoped keys from {len(a.pairs)} worlds', file=sys.stderr)


if __name__ == '__main__':
    main()
