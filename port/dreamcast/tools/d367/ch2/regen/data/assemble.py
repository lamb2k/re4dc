"""assemble.py: rebuild the data sets ch2 (/root/re4data/private/ch2data-20261016) and cast16
(/root/re4data/private/cast16data-20261016) that the n3-c4w-r10f fixture used, from sha-verified recovered or
regenerated files. Every file must match the target sha of payload-manifest.json for its disc path; files with no
verified source are listed (missing.json) and left out. ch2-data.json: replace (disc path -> copy), unremove =
the ch2 disc paths (see report), provenance (source of each file)."""
import hashlib, json, os, shutil, sys
E = '/mnt/c/Flycast-Evidence/re4-dreamcast/ch2code-20261016/n3-c4w-r10f'
L = '/root/probe/lanes-20261017r/ch2regen'
A = '/mnt/c/Game Dev/Emulators/re4-assets-private/ch2regen-20261018'
man = json.load(open(E + '/payload-manifest.json'))
fix = json.load(open(E + '/stage.json'))['fixture']['replace']
sets = {'ch2': '/root/re4data/private/ch2data-20261016', 'cast16': '/root/re4data/private/cast16data-20261016'}
todo = {}
for path, src in fix.items():
    for name, root in sets.items():
        if src.startswith(root + '/files/'):
            todo[path] = (name, src[len(root) + 7:])
want = {}
for path in todo:
    want.setdefault(man[path]['sha256'], []).append(path)
sizes = {man[p]['size'] for p in todo}
found = {}
dirs = [A, L + '/t163', L + '/rooms', L + '/worlds', L + '/luis', L + '/r11d', L + '/regs', L + '/em16', L + '/snd',
        L + '/ps2cast', L + '/src', L + '/resrc/final']
extra = [L + '/tex-13340bfa.pak']
def consider(p):
    try:
        s = os.path.getsize(p)
    except OSError:
        return
    if s not in sizes or os.path.islink(p):
        return
    h = hashlib.sha256(open(p, 'rb').read()).hexdigest()
    for path in want.get(h, []):
        found.setdefault(path, p)
for d in dirs:
    for dp, dn, fn in os.walk(d):
        for f in fn:
            consider(os.path.join(dp, f))
for p in extra:
    consider(p)
# survivor maps from cover.py runs (disc path -> surviving file), sha re-checked
S = '/mnt/c/Users/lambd/AppData/Local/Temp/claude/C--Game-Dev-Emulators/c357f0f1-ecb5-45e4-b858-3f1d8ec8cd20/scratchpad/ch2regen'
for cj in ('cover-wsl.json', 'cover-rem.json', 'cover-rem2.json', 'cover-rem4.json'):
    try:
        for path, src in json.load(open(S + '/' + cj)).items():
            if path in todo and path not in found and os.path.exists(src):
                if hashlib.sha256(open(src, 'rb').read()).hexdigest() == man[path]['sha256']:
                    found[path] = src
    except FileNotFoundError:
        pass
# tex.pak entries (stored verbatim): the 16.3 base pak and the recovered/rebuilt paks; extracted to $L/pakx
import struct
os.makedirs(L + '/pakx', exist_ok=True)
for pk in [L + '/t163/dc/tex.pak', L + '/tex-13340bfa.pak']:
    b = open(pk, 'rb').read()
    n, io = struct.unpack_from('<2I', b, 12)
    for i in range(n):
        c, f, o, z = struct.unpack_from('<4I', b, io + 16 * i)
        if z not in sizes: continue
        h = hashlib.sha256(b[o:o + z]).hexdigest()
        for path in want.get(h, []):
            if path in found: continue
            q = L + '/pakx/' + os.path.basename(path); open(q, 'wb').write(b[o:o + z]); found[path] = q
rep = {n: {} for n in sets}; prov = {}; missing = []
for path, (name, rel) in sorted(todo.items()):
    if path not in found:
        missing.append(path); continue
    dst = sets[name] + '/files/' + rel
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(found[path], dst)
    rep[name][path] = dst; prov[path] = found[path]
json.dump({'replace': rep['ch2'], 'unremove': sorted(rep['ch2']), 'provenance': {'ch2regen': 'assemble.py 2026-10-17', 'sources': {k: prov[k] for k in rep['ch2']}, 'missing': [m for m in missing if todo[m][0] == 'ch2']}},
          open(sets['ch2'] + '/ch2-data.json', 'w'), indent=1, sort_keys=True)
json.dump({'about': 'cast16 data set regenerated by lane ch2regen (2026-10-17)', 'replace': rep['cast16'],
           'sha256': {k: man[k]['sha256'] for k in rep['cast16']}}, open(sets['cast16'] + '/cast16-data.json', 'w'), indent=1)
json.dump(missing, open(L + '/assemble-missing.json', 'w'), indent=0)
print({n: len(v) for n, v in rep.items()}, 'of', {n: sum(1 for v in todo.values() if v[0] == n) for n in sets}, 'missing', len(missing))
print(missing[:30])
