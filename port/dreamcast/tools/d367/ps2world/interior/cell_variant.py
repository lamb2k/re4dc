#!/usr/bin/env python3
"""cell_variant.py: the PS2_INTERIOR_CULL cell for a re-exported r100 package with the same geometry (lane world-n256all
2026-10-26, SCENERY_N256: the r100 world at 256-vertex meshlets).

    cell_variant.py <cfg.json> <base mesh> <base r4pw> <base .cell> <new mesh> <new r4pw> <out .cell> <out .inc>

The cell's sub-cells and portals are a function of the package's occluders only (build_cell.py occluders(): every opaque
level-0 triangle in the occluder box, with its one/two-sided flag). This tool proves that the new package has exactly the
same occluder set as the base package the shipped cell file belongs to (both sorted, compared bit for bit), then writes:
  - <out .cell>: the base cell file with its PCL1 header bound to the new package (mesh crc, mesh bytes; room, sidecar
    crc, counts, cells and portals byte-identical: cell_file.py pack of the same tables);
  - <out .inc>: the constants the runtime selects under SCENERY_N256=1 (kPcN256MeshUse, kPcN256MeshBytesUse).
A package whose occluders differ is refused: rebuild the cell with build_cell.py prepare / cast_cell.sh / emit instead.
"""
import hashlib, struct, sys
from pathlib import Path
import json
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from r4im import Pkg  # noqa: E402
from build_cell import occluders  # noqa: E402
from cell_file import pack  # noqa: E402


def occ(cfg, mesh, side):
    t, two = occluders(cfg, Pkg(mesh, side))
    rows = np.concatenate([t.reshape(len(t), -1).astype(np.float64), two.reshape(-1, 1).astype(np.float64)], 1)
    return rows[np.lexsort(rows.T[::-1])]


def main():
    cfg_p, bm, bs, bc, nm, ns, oc, oi = sys.argv[1:9]
    cfg = json.loads(Path(cfg_p).read_text())
    base = Path(bc).read_bytes()
    h = struct.unpack_from('<4s7I', base, 0)
    bmesh = Path(bm).read_bytes(); nmesh = Path(nm).read_bytes()
    bcrc, bbytes = struct.unpack_from('<I', bmesh, 12)[0], len(bmesh)
    ncrc, nbytes = struct.unpack_from('<I', nmesh, 12)[0], len(nmesh)
    assert h[0] == b'PCL1' and h[2] == bcrc and h[4] == bbytes, 'base cell does not belong to the base package'
    assert Path(bs).read_bytes() == Path(ns).read_bytes(), 'sidecars differ'
    a = occ(cfg, bm, bs); b = occ(cfg, nm, ns)
    if a.shape != b.shape or not np.array_equal(a, b):
        sys.exit('occluder sets differ (%s vs %s): rebuild the cell with build_cell.py' % (a.shape, b.shape))
    n_cells, n_portals = h[5], h[6]
    cells = [(list(r[0:3]), list(r[3:6]), r[6], r[7]) for r in struct.iter_unpack('<6f2H', base[32:32 + 28 * n_cells])]
    portals = list(struct.iter_unpack('<I5f', base[32 + 28 * n_cells:32 + 28 * n_cells + 24 * n_portals]))
    out = pack(h[1], ncrc, h[3], nbytes, cells, portals)
    assert out[20:] == base[20:] and len(out) == len(base)
    Path(oc).write_bytes(out)
    sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
    Path(oi).write_text('\n'.join([
        '// Generated by tools/d367/ps2world/interior/cell_variant.py; do not edit.',
        f'// SCENERY_N256=1: the r100 package at 256-vertex meshlets (ps2-world.re4mesh sha256 {sha(nm)}) has the same',
        f'// {len(a)} occluder triangles as the base package (sha256 {sha(bm)}), so the same {n_cells} sub-cells and',
        f'// {n_portals} portals; the disc cell file ({sha(oc)[:16]}) carries this package\'s crc and bytes.',
        f'constexpr unsigned kPcN256MeshUse=0x{ncrc:08x}U,kPcN256MeshBytesUse={nbytes}U;', '']), newline='\n')
    print(f'cell variant: {len(a)} occluders identical; mesh {bcrc:08x}/{bbytes} -> {ncrc:08x}/{nbytes}; {oc}')


if __name__ == '__main__':
    main()
