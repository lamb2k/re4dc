#!/usr/bin/env python3
"""fx_none_cut_pack.py <fx_none_cut.inc> <fx_none_cut_pack.inc>  (lane heap-margin25, 2026-10-25)

FX_NONE_CUT_PACK=1 (effects30.mk): the FX_PS2_NONE_CUT table in a smaller static form with the same answers.
fx_none_cut.inc stores one 12-byte row {room, crc, fnv} per (room, key): 469 rows, 245 distinct keys. The packed
form stores each key once (8 bytes) and the rows as one-byte key indices grouped by room:
  kFxPackKeys[]       {crc, fnv}, distinct keys in first-seen order;
  kFxPackRoom[]       the rooms that have rows (0xffff = the any-room rows), ascending;
  kFxPackBeg[]        start of each room's indices in kFxPackIdx (one extra end entry);
  kFxPackIdx[]        key indices.
kFxNoneRooms (the library rooms) is copied unchanged. A key is cut in `room` exactly when the original test holds:
some row has the key and (row.room == room, or row.room == 0xffff and room is not a library room).
"""
import re
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src).read()
    m = re.search(r"kFxNoneRooms\[\] = \{([^}]*)\}", text)
    if not m:
        sys.exit("fx_none_cut_pack: kFxNoneRooms not found")
    lib = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]
    rows = [(int(r, 16), int(c, 16), int(f, 16))
            for r, c, f in re.findall(r"\{(0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+)\}", text)]
    if not rows:
        sys.exit("fx_none_cut_pack: no rows")
    keys, kidx = [], {}
    for _, c, f in rows:
        if (c, f) not in kidx:
            kidx[(c, f)] = len(keys)
            keys.append((c, f))
    if len(keys) > 256:
        sys.exit("fx_none_cut_pack: %d keys do not fit a one-byte index" % len(keys))
    rooms = sorted(set(r for r, _, _ in rows))
    by_room = {r: [] for r in rooms}
    for r, c, f in rows:
        i = kidx[(c, f)]
        if i not in by_room[r]:
            by_room[r].append(i)
    idx, beg = [], []
    for r in rooms:
        beg.append(len(idx))
        idx.extend(by_room[r])
    beg.append(len(idx))
    # Self-check: the packed test equals the original for every (room, key) pair over all rooms seen plus a non-library room.
    libset = set(lib)
    for room in set(rooms) | libset | {0x999}:
        for k in keys:
            orig = any((c, f) == k and (r == room or (r == 0xFFFF and room not in libset)) for r, c, f in rows)
            ki = kidx[k]
            new = False
            for j, r in enumerate(rooms):
                if r == room or (r == 0xFFFF and room not in libset):
                    if ki in idx[beg[j]:beg[j + 1]]:
                        new = True
            if orig != new:
                sys.exit("fx_none_cut_pack: mismatch room %x key %08x-%08x" % (room, k[0], k[1]))
    out = []
    out.append("// Generated by tools/d367/purge-fx24/fx_none_cut_pack.py from fx_none_cut.inc. Do not edit.")
    out.append("// %d rows -> %d keys, %d rooms, %d indices." % (len(rows), len(keys), len(rooms), len(idx)))
    out.append("static const unsigned short kFxNoneRooms[] = {%s};" % ", ".join("0x%x" % r for r in lib))
    out.append("static const FxPackKey kFxPackKeys[] = {")
    for c, f in keys:
        out.append("    {0x%08x, 0x%08x}," % (c, f))
    out.append("};")
    out.append("static const unsigned short kFxPackRoom[] = {%s};" % ", ".join("0x%x" % r for r in rooms))
    out.append("static const unsigned short kFxPackBeg[] = {%s};" % ", ".join(str(b) for b in beg))
    out.append("static const unsigned char kFxPackIdx[] = {")
    for i in range(0, len(idx), 24):
        out.append("    " + ", ".join(str(x) for x in idx[i:i + 24]) + ",")
    out.append("};")
    open(dst, "w").write("\n".join(out) + "\n")
    print("fx_none_cut_pack: %d rows -> %d keys %d rooms %d indices" % (len(rows), len(keys), len(rooms), len(idx)))


if __name__ == "__main__":
    main()
