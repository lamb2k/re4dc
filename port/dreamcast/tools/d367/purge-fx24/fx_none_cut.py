#!/usr/bin/env python3
"""fx_none_cut.py: the FX_PS2_NONE_CUT table (lane purge-fx24, 2026-10-24; render only, default-off knob).

  fx_none_cut.py <ps2lib root> <out .inc>

The PS2 effect library (ps2lib/effects-tex, fx_ps2_pack.py lib) has one INDEX.tsv row per GameCube effect texture id;
ps2_source=NONE means the PS2 room EFF that pairs with the GameCube one has no picture with that id, so every PS2
record that drew it is gone: the PS2 dropped that effect. effects-tex/KEYS.tsv maps each (room, id, frame) to the
tex.pak key the game looks up. This writes:
  kFxNoneRooms[]  the library's rooms (their own rows decide);
  kFxNoneCut[]    {room, crc, fnv}: one row per (room, key) whose every library row in that room is NONE;
                  room 0xffff: keys whose every library row in every folder (rooms, common, em, wep) is NONE,
                  applied only in rooms the library does not cover (ch2 r10c..r11f, r200, ...).
A key with any converted row in the same room (or, for 0xffff, anywhere) is never cut.
"""
import csv, sys
from pathlib import Path


# Rows converted from a PS2 file other than the room's own (fx_cross_room.py PAIRS, coordinator 10-24): not cut.
CROSS_ROOM = {('r117', 'st1/r117.arc#7:0x86')}   # church candle flames <- PS2 r10e.dat EFF #7 0x86 (data set pfx24)


def room_id(name):
    return int(name[1:], 16) if name.startswith('r') and len(name) == 4 else None


def main(libroot, out):
    lib = Path(libroot)
    rows = [r for r in csv.reader(open(lib / 'INDEX.tsv', encoding='utf-8'), delimiter='\t')
            if r and r[0] == 'effects-tex']
    none = {(r[1], r[2]): r[3] == 'NONE' and (r[1], r[2]) not in CROSS_ROOM for r in rows}
    per_room, per_key = {}, {}
    for r in list(csv.reader(open(lib / 'effects-tex/KEYS.tsv', encoding='utf-8'), delimiter='\t'))[1:]:
        key, folder, gid = r[0], r[1], r[2]
        st = none.get((folder, gid))
        if st is None:
            continue
        per_room.setdefault((folder, key), set()).add(st)
        per_key.setdefault(key, set()).add(st)
    rooms = sorted({room_id(f) for f, _ in none if room_id(f) is not None})
    # lane fix-r100-props26 (2026-10-26): a key converted from a PS2 picture in ANY library row is never cut. The
    # matcher pairs a room's GameCube EFF only with that room's PS2 EFF, by id; the same picture under the same
    # key is often found in another PS2 file (r102 / r108 candles = PS2 r10e 0x86, r105 candle = PS2 r102 0x85, r103
    # 0xd9 = PS2 r100 0xd9): its tex.pak package is already the PS2 picture, and the PS2 draws that effect.
    cut = sorted((room_id(f), k) for (f, k), s in per_room.items()
                 if s == {True} and per_key[k] == {True} and room_id(f) is not None)
    wild = sorted(k for k, s in per_key.items() if s == {True})
    lines = ['// Generated by tools/d367/purge-fx24/fx_none_cut.py from ps2lib effects-tex (INDEX.tsv NONE rows + KEYS.tsv).',
             '// %d library rooms, %d room rows, %d any-room rows. Do not edit.' % (len(rooms), len(cut), len(wild)),
             'static const unsigned short kFxNoneRooms[] = {%s};' % ', '.join('0x%03x' % x for x in rooms),
             'static const FxNoneCutRow kFxNoneCut[] = {']
    for room, k in cut:
        c, f = k.split('-')
        lines.append('    {0x%03x, 0x%s, 0x%s},' % (room, c, f))
    for k in wild:
        c, f = k.split('-')
        lines.append('    {0xffff, 0x%s, 0x%s},' % (c, f))
    lines.append('};')
    Path(out).write_text('\n'.join(lines) + '\n')
    print('fx_none_cut: rooms=%d room_rows=%d any_room_rows=%d' % (len(rooms), len(cut), len(wild)))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
