#!/usr/bin/env python3
"""Emit EF13's bounded, source-bound spans from the public compiled water tables.

The two input includes are already generated from their PS2 sources. Their row
comments retain the exact source EFF family; this tool checks that provenance,
room grouping and bounds before writing the metadata consumed by espgen45.cpp.
It needs no disc, cache or private package.
"""
import argparse
from collections import OrderedDict
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[5]
MAIN = ROOT / "src/game/water_ps2_table.inc"
EXT = ROOT / "src/game/water_ps2_ext.inc"
OUT = ROOT / "src/game/water_layer29_source.inc"


def source_key(name):
    value = 2166136261
    for byte in name.encode("ascii"):
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value


def table(path, suffix):
    rows = OrderedDict()
    last_room = None
    row_index = 0
    for line in path.read_text().splitlines():
        if not line.lstrip().startswith("{0x"):
            continue
        match = re.match(r"\s*\{0x([0-9a-fA-F]+),", line)
        assert match and "//" in line, f"malformed row: {path}:{row_index}"
        room = int(match.group(1), 16)
        provenance = line.split("//", 1)[1].strip()
        family_match = re.match(r"(r[0-9a-fA-F]{3}" + suffix + r")\b", provenance)
        assert family_match, f"missing source EFF family: {path}:{row_index}"
        family = family_match.group(1)
        assert int(family[1:4], 16) == room, f"room/source mismatch: {path}:{row_index}"
        if room not in rows:
            rows[room] = [row_index, 0, family]
        else:
            assert room == last_room, f"noncontiguous room span: {path}:{row_index}"
            assert rows[room][2] == family, f"mixed source families: {path}:{row_index}"
        rows[room][1] += 1
        last_room = room
        row_index += 1
    assert row_index > 0, f"no rows: {path}"
    return rows


def render(main_path=MAIN, ext_path=EXT):
    main = table(main_path, r"\.ps2\.eff[0-9]+")
    ext = table(ext_path, r"\.dat eff[0-9]+")
    assert set(main).isdisjoint(ext), "main and extension room identities overlap"
    keys = [source_key(row[2]) for row in (*main.values(), *ext.values())]
    assert len(set(keys)) == len(keys), "source-family key collision"
    lines = [
        "// GENERATED by port/dreamcast/tools/d367/water/water_layer29_source.py from the checked-in",
        "// water_ps2_table.inc and water_ps2_ext.inc row provenance. Do not edit by hand.",
        "enum { WATER29_SOURCE_VERSION = 1 };",
        "struct Water29SourceSpan { u16 room; uint32_t source_key; u8 main_first, main_count, ext_first, ext_count; };",
        "static const Water29SourceSpan kWater29SourceSpans[] = {",
    ]
    for room, (first, count, family) in main.items():
        assert first + count <= 255 and count <= 32
        lines.append(f"    {{0x{room:03x}, 0x{source_key(family):08x}u, {first}, {count}, 0, 0}}, // {family}")
    lines.append("#if defined(RE4DC_WATER_PS2_EXT) && RE4DC_WATER_PS2_EXT")
    for room, (first, count, family) in ext.items():
        assert first + count <= 255 and count <= 32
        lines.append(f"    {{0x{room:03x}, 0x{source_key(family):08x}u, 0, 0, {first}, {count}}}, // {family}")
    lines += ["#endif", "};", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--main", type=Path, default=MAIN)
    ap.add_argument("--ext", type=Path, default=EXT)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    args.out.write_text(render(args.main, args.ext))


if __name__ == "__main__":
    main()
