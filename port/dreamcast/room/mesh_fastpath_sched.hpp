// MESH_VP_SCHED (default off): the meshlet transform's kChecksAll loop (mesh_fastpath.hpp transform<>)
// software-pipelined over two vertices. Iteration j issues vertex j's loads, int->float conversions and FTRV
// first; vertex j-1's x/y * 1/w products, its z/y/x stores and its four screen outcode compares fill the FTRV
// latency; then vertex j's depth compares, the 1/w chain (w*w, FSRRA: consumed one iteration later), u/v and
// colour. Every per-vertex FP operation and operand is the original's (same FTRV, the same w*w FSRRA form,
// the same fmac order for u/v, the same colour LUT words), so the cache entries are bit-identical; the outcode
// byte's defined bits (screen bits 5..2, depth bits 1..0) are identical, the don't-care bits 7..6 differ (the
// original rotates argb bits into them; consumers mask with screen_mask/depth_mask).
//
// Registers: fr7..fr15 the same constants; fr0..fr3 vertex j's FTRV vector (then its u/v accumulators fr2/fr3);
// fr4 1/w of vertex j-1 (FSRRA in flight across the back edge); fr5/fr6 x/y of vertex j-1. The constant-block
// pointer becomes the depth-bit register after the prologue; r1 holds the screen bits; the colour word has its
// own register (%[c]: its lifetime overlaps the screen bits').
// Stores: one pre-decrementing pointer, back(j-1) z/y/x then (+56) front(j) argb/v/u, so the pointer advances
// once per vertex exactly as before. Reads: exactly the original's (the 3 words of each vertex in order, the
// two LUT words, the same PREF addresses); no read past the meshlet.
