#!/usr/bin/env python3
"""gen_wraps.py: --wrap trampolines for the service census build of re4ref (lane eng-svc).

    gen_wraps.py <out.S> <out_names.c> <out.flags> S:<obj>... M:<obj>...

Every global function symbol defined in the listed objects gets `-Wl,--wrap=<sym>` and an i386 trampoline:

  S (service entry: skeleton, collision and the other service units): counts the call (census_hit(idx, return
    address, first argument)), pushes the caller's return address on the census shadow stack and returns
    through census_back, so the tracer knows which service call is running (census_sp > 0) and its outermost entry.
  M (math and memory helpers: the SDK matrix and vector library, the game's math_sub / sub2, fdlibm, memcpy /
    memset): counts the call and pushes the return address on the math stack (census_msp), so a memory access
    inside a helper is attributed to the helper's caller. The service context is unchanged.

--wrap rewrites undefined references only: a call inside one object (motion.o calling its own MotionMoveCore) is
not counted, a call across objects (player.o calling MotionMove) is. That is the service boundary.
census_back / census_mback clobber only ecx and the flags, so integer (eax:edx) and x87 (st0) results pass.
"""
import subprocess
import sys


def defined_functions(obj):
    out = subprocess.run(["nm", "--defined-only", "-g", obj], capture_output=True, text=True, check=True).stdout
    syms = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ("T", "W"):
            syms.append(parts[2])
    return syms


def main():
    out_s, out_c, out_flags = sys.argv[1:4]
    seen = {}
    order = []
    for arg in sys.argv[4:]:
        kind, obj = arg.split(":", 1)
        unit = obj.rsplit("/", 1)[-1].rsplit(".", 1)[0]
        for s in defined_functions(obj):
            if s in seen or s.startswith("__wrap_") or s.startswith("__real_") or s in ("main", "_start"):
                continue
            seen[s] = (kind, unit)
            order.append(s)
    for extra in ("memcpy", "memset", "memmove"):
        if extra not in seen:
            seen[extra] = ("M", "libc")
            order.append(extra)
    with open(out_s, "w") as f:
        f.write("# generated by gen_wraps.py: census trampolines (see there)\n")
        for i, s in enumerate(order):
            kind, _ = seen[s]
            # one section per trampoline: --gc-sections drops the ones nobody calls (and the functions they name)
            f.write('\t.section .text.__wrap_%s,"ax",@progbits\n' % s)
            f.write("\t.globl __wrap_%s\n\t.type __wrap_%s,@function\n__wrap_%s:\n" % (s, s, s))
            f.write("\tpushl 4(%%esp)\n\tpushl 4(%%esp)\n\tpushl $%d\n\tcall census_hit\n\taddl $12,%%esp\n" % i)
            if kind == "S":
                f.write("\tmovl census_sp,%ecx\n\tmovl (%esp),%edx\n\tmovl %edx,census_ret(,%ecx,4)\n")
                f.write("\tmovl $%d,census_idx(,%%ecx,4)\n\tmovl 4(%%esp),%%edx\n\tmovl %%edx,census_arg(,%%ecx,4)\n" % i)
                f.write("\tincl %ecx\n\tmovl %ecx,census_sp\n\tmovl $census_back,(%esp)\n")
            else:
                f.write("\tmovl census_msp,%ecx\n\tmovl (%esp),%edx\n\tmovl %edx,census_mret(,%ecx,4)\n")
                f.write("\tincl %ecx\n\tmovl %ecx,census_msp\n\tmovl $census_mback,(%esp)\n")
            f.write("\tjmp __real_%s\n" % s)
        f.write('\t.section .text.census_back,"ax",@progbits\n')
        f.write("\t.globl census_back\ncensus_back:\n\tdecl census_sp\n\tmovl census_sp,%ecx\n"
                "\tmovl census_ret(,%ecx,4),%ecx\n\tjmp *%ecx\n")
        f.write("\t.globl census_mback\ncensus_mback:\n\tdecl census_msp\n\tmovl census_msp,%ecx\n"
                "\tmovl census_mret(,%ecx,4),%ecx\n\tjmp *%ecx\n")
        f.write('\t.section .note.GNU-stack,"",@progbits\n')
    with open(out_c, "w") as f:
        f.write("/* generated by gen_wraps.py */\n")
        f.write("extern \"C\" {\nextern unsigned census_nsyms;\nextern const char* const census_name[];\n")
        f.write("extern const char* const census_unit[];\nextern const char census_kind[];\n")
        f.write("unsigned census_nsyms = %d;\nconst char* const census_name[] = {\n" % len(order))
        for s in order:
            f.write('  "%s",\n' % s)
        f.write("};\nconst char* const census_unit[] = {\n")
        for s in order:
            f.write('  "%s",\n' % seen[s][1])
        f.write("};\nconst char census_kind[] = \"%s\";\n}\n" % "".join(seen[s][0] for s in order))
    with open(out_flags, "w") as f:
        f.write(" ".join("-Wl,--wrap=%s" % s for s in order) + "\n")


if __name__ == "__main__":
    main()
