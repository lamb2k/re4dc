#!/usr/bin/env python3
"""gen_stubs.py (lane eng-e2, from hostref/gen_stubs.py of lane eng-host2): logging stubs for the symbols the hosted
Ganados and room script reach that the E2 fight image does not host (SH-4, the engine image).

    gen_stubs.py UNDEF.txt OUT.cpp [--kinds KINDS.tsv]

UNDEF.txt: the link's undefined references with mangled names (one per line: the `undefined reference to
`NAME'` lines of a -Wl,--no-demangle link, or bare names). Each becomes a function that logs the call
(host_stub_hit: counted, hashed and named in the trace's stub field) and returns zero of the declared return
type, defined under the referenced link name:

    extern "C" RET hs_N(...) asm("MANGLED");
    RET hs_N(...) { host_stub_hit("DEMANGLED"); return hr_z<RET>::get(); }

RET is the declaration's own return type, taken by the compiler from the game's headers (decltype of a call
to the declared function or member), so a float or double comes back in the x87 register the caller pops
and a structure through the caller's hidden pointer. The ellipsis takes any arguments: on the i386 the
caller pushes and pops them (cdecl, `this` first for members), so the stub needs no parameter list.
Names the headers do not declare fall back to an int return (listed as such in the output's comments).
The generated file is committed; rerun after a closure change. Object (data) symbols are not handled:
they are host adapters (host_globals.cpp, host_actors.cpp).
"""
import re
import subprocess
import sys

FILT = 'sh-elf-c++filt'
HEADERS = ['global.h', 'main.h', 'joy.h', 'pad.h', 'model.h', 'em.h', 'obj.h', 'player.h', 'pl_npc.h', 'pl_sub.h',
           'pl_wep.h', 'em10.h', 'em_sub.h', 'em_set.h', 'emhit.h', 'emwep.h', 'emdoor.h', 'emwindow.h',
           'emswitch.h', 'emshield.h', 'emrack.h', 'embarrel.h', 'at_mod.h', 'atari.h', 'esp.h', 'est.h', 'ctrl.h',
           'snd.h', 'quake.h', 'act_btn.h', 'cockpit.h', 'camera.h', 'cam_ctrl.h', 'route_ck.h', 'foot_shadow.h',
           'dbmodule.h', 'mercenaries.h', 'motion.h', 'game.h', 'rnd.h', 'math_sub.h', 'db_log.h', 'em_cloth.h',
           'item.h', 'sce_at.h', 'sce.h', 'gx_sub.h', 'light.h', 'dmg.h', 'map_obj.h', 'widget.h', 'sscrn.h',
           'objBull.h', 'pendulum.h', 'pl_cloth.h', 'emdoor.h', 'eprintf.h', 'cMotBase.h', 'sce_at.h', 'sce_sys.h',
           'scheduler.h', 'mes.h', 'id_sys.h', 'ss_main.h', 'event.h', 'obj16.h', 'emshield.h',
           'room_data.h', 'datactrl.h', 'cockpit.h', 'filter.h', 'mercenaries.h', 'item.h', 'etc_model.h', 'em_wrap.h', 'emwindow.h']


def demangle(names):
    p = subprocess.run([FILT], input='\n'.join(names), capture_output=True, text=True)
    return dict(zip(names, p.stdout.split('\n')))


def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '(<[':
            depth += 1
        elif ch in ')>]':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [a for a in out if a != 'void']


def parse(dm):
    """-> (qualifier, name, args, const) for 'A::B::f(T1, T2) const', or None for a C name / data."""
    m = re.match(r'^(.*?)\((.*)\)( const)?$', dm)
    if not m:
        return None
    full, args, const = m.group(1), m.group(2), bool(m.group(3))
    if '(anonymous namespace)' in full or 'operator' in full:
        return None
    parts = full.split('::')
    return '::'.join(parts[:-1]), parts[-1], split_args(args), const


def ret_expr(mangled, dm):
    p = parse(dm)
    if p is None:
        if mangled.startswith('_Z') or not re.match(r'^[A-Za-z_]\w*$', mangled):
            return None
        return 'decltype(hr_ret(&%s))' % mangled   # a C name: its declared function type
    qual, name, args, const = p
    call_args = ', '.join('hr_v<%s>()' % a for a in args)
    if qual and (name == qual.split('::')[-1] or name.startswith('~')):
        return 'void'   # constructor / destructor
    if qual:
        obj = 'hr_v<%s%s&>()' % ('const ' if const else '', qual)
        return 'decltype(%s.%s(%s))' % (obj, name, call_args)
    return 'decltype(%s(%s))' % (name, call_args)


PRE = '''// E2 fight image (lane eng-e2): logging stubs for what the hosted Ganados and the room script reach that this image
// does not host: other characters' objects (weapons, shields, carts), doors, windows, ladders, items, messages, the
// HUD's sub screens, sound streams, room controllers. GENERATED by engine/fight/gen_stubs.py from the link's undefined
// references; each stub logs the call (e1_stub_hit: the report's stub counts) and returns zero of the declared type.
#include "e1_engine.h"
#include <string.h>
%s
template<class T> T&& hr_v();   // unevaluated: an expression of type T
template<class R, class... A> R hr_ret(R (*)(A...));
template<class R, class... A> R hr_ret(R (*)(A..., ...));
template<class T> struct hr_z { static T get() { alignas(16) static unsigned char z[sizeof(T)]; return *(T*) z; } };
template<class T> struct hr_z<T&> { static T& get() { alignas(16) static unsigned char z[sizeof(T)]; return *(T*) z; } };
template<> struct hr_z<void> { static void get() {} };
#define HS(n) e1_stub_hit(n, 0)
'''


def main():
    undef, out = sys.argv[1], sys.argv[2]
    names = []
    for line in open(undef):
        m = re.search(r"undefined reference to `([^']+)'", line)
        n = m.group(1) if m else line.strip()
        if n and n not in names:
            names.append(n)
    dm = demangle(names)
    fallback = set(sys.argv[3].split(',')) if len(sys.argv) > 3 and sys.argv[3] else set()
    body = []
    for i, n in enumerate(sorted(names)):
        c = n[1:] if n.startswith('_') and not n.startswith('__Z') else n   # SH-ELF: C names carry a leading underscore
        d = dm.get(n, n)
        if c != n:
            d = c
        r = None if n in fallback else ret_expr(c, d)
        note = ''
        if r is None:
            r = 'int'
            note = '   // not declared in the headers: int'
        body.append('// %s%s' % (d, note))
        body.append('extern "C" %s hs_%d(...) asm("%s");' % (r, i, n))
        body.append('%s hs_%d(...) { HS("%s"); return hr_z<%s>::get(); }' % (r, i, d.replace('"', '\\"'), r))
    incs = '\n'.join('#include "%s"' % h for h in dict.fromkeys(HEADERS))
    with open(out, 'w') as f:
        f.write(PRE % incs)
        f.write('\n'.join(body) + '\n')
    print('gen_stubs: %d stubs' % len(names))


if __name__ == '__main__':
    main()
