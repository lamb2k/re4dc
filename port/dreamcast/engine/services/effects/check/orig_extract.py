#!/usr/bin/env python3
"""orig_extract.py <out.cpp> <src.cpp>:NAME[,NAME...] ...  (lane eng-e2, effect equivalence check)

The original effect functions the check runs, copied verbatim from src/ after the preprocessor has resolved their
#if branches with every RE4DC_ knob off (the form the original game's logic has): each NAME (`Class::method` or a plain
function) is the definition whose signature line names it, through its matching closing brace. A `#line` directive
before each copy points the compiler's messages back to the source file. Nothing in a copied body is changed.
"""
import re
import subprocess
import sys


def preprocess(src, flags):
    # keep line markers so each copy can carry its source position; macros and #if resolved, comments removed
    p = subprocess.run(['g++', '-E', '-x', 'c++'] + flags + [src], capture_output=True, text=True)
    if p.returncode:
        sys.exit(p.stderr[-2000:])
    return p.stdout


def find(text, name):
    """(line number in src, body) of each definition of `name` in the preprocessed text of the source file."""
    lines = text.split('\n')
    cur_file, cur_line, out = None, 0, []
    pat = re.compile(r'(^|[\s\*&])' + re.escape(name) + r'\s*\(')
    i = 0
    while i < len(lines):
        l = lines[i]
        m = re.match(r'^# (\d+) "([^"]+)"', l)
        if m:
            cur_line, cur_file = int(m.group(1)), m.group(2); i += 1; continue
        if cur_file and cur_file.endswith(SRC_BASENAME) and pat.search(l) and not l.rstrip().endswith(';') \
                and not l.startswith((' ', '\t')):
            # a definition: braces from here
            body, depth, started, j = [], 0, False, i
            while j < len(lines):
                t = lines[j]
                if re.match(r'^# \d+ "', t):
                    j += 1; continue
                body.append(t)
                depth += t.count('{') - t.count('}')
                if '{' in t: started = True
                if started and depth == 0: break
                if not started and t.rstrip().endswith(';'): body = None; break
                j += 1
            if body:
                out.append((cur_line, '\n'.join(body)))
            cur_line += j - i + 1
            i = j + 1
            continue
        cur_line += 1
        i += 1
    return out


if __name__ == '__main__':
    out = sys.argv[1]
    flags, specs, args = [], [], sys.argv[2:]
    i = 0
    while i < len(args):
        if args[i] in ('-include', '-isystem'):
            flags += args[i:i + 2]; i += 2; continue
        (flags if args[i].startswith('-') else specs).append(args[i]); i += 1
    parts = ['// GENERATED by services/effects/check/orig_extract.py: original effect functions, verbatim (knobs off).']
    for spec in specs:
        src, names = spec.split(':', 1)
        SRC_BASENAME = src.split('/')[-1]
        text = preprocess(src, flags)
        for name in names.replace('+', ' ').split(','):
            defs = find(text, name)
            if not defs:
                sys.exit('%s: %s not found' % (src, name))
            for line, body in defs:
                parts.append('#line %d "%s"' % (line, src))
                parts.append(body)
    open(out, 'w').write('\n'.join(parts) + '\n')
    print('orig_extract: %d specs' % len(specs))
